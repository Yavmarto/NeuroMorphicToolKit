import uuid

import pytest
from fastapi import FastAPI
from fastapi.testclient import TestClient

from backend.app.middleware.request_id import RequestIDMiddleware, get_request_id

# Use a minimal isolated app so test routes are registered before first request
app = FastAPI()
app.add_middleware(RequestIDMiddleware)


@app.get("/health")
def health_check():
    return {"status": "ok"}


@app.get("/test-request-id-ctx")
def get_ctx_request_id():
    return {"ctx_request_id": get_request_id()}


@app.get("/test-request-id-error")
def raise_error():
    raise ValueError("Test error for request ID")


client = TestClient(app)


def test_request_id_in_response_header():
    """Verify that X-Request-ID is present in the response headers."""
    response = client.get("/health")
    assert "X-Request-ID" in response.headers
    # Check if it's a valid UUID
    try:
        uuid.UUID(response.headers["X-Request-ID"])
    except ValueError:
        pytest.fail("X-Request-ID is not a valid UUID")


def test_request_id_uniqueness():
    """Verify that each request gets a unique X-Request-ID."""
    response1 = client.get("/health")
    response2 = client.get("/health")
    assert response1.headers["X-Request-ID"] != response2.headers["X-Request-ID"]


def test_request_id_preservation():
    """Verify that X-Request-ID from request headers is preserved in the response."""
    request_id = str(uuid.uuid4())
    response = client.get("/health", headers={"X-Request-ID": request_id})
    assert response.headers["X-Request-ID"] == request_id


def test_request_id_in_context():
    """Verify that get_request_id() returns the correct ID within a request."""
    request_id = str(uuid.uuid4())
    response = client.get("/test-request-id-ctx", headers={"X-Request-ID": request_id})
    assert response.status_code == 200
    assert response.json()["ctx_request_id"] == request_id
    assert response.headers["X-Request-ID"] == request_id


