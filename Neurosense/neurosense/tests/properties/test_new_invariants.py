@given(from_state=st.sampled_from(DeviceState), to_state=st.sampled_from(DeviceState))
def test_connection_transition_invariants(from_state: DeviceState, to_state: DeviceState) -> None:
    """Verify all state transitions according to the contract."""
    valid_transitions = {
        DeviceState.DISCONNECTED: {DeviceState.CONNECTING},
        DeviceState.CONNECTING: {
            DeviceState.CONNECTED,
            DeviceState.ERROR,
            DeviceState.DISCONNECTED,
        },
        DeviceState.CONNECTED: {DeviceState.DISCONNECTING, DeviceState.ERROR},
        DeviceState.DISCONNECTING: {DeviceState.DISCONNECTED, DeviceState.ERROR},
        DeviceState.ERROR: {DeviceState.DISCONNECTED, DeviceState.CONNECTING},
    }

    is_valid = to_state in valid_transitions[from_state] or from_state == to_state

    if is_valid:
        ConnectionTransition(from_state=from_state, to_state=to_state)
    else:
        with pytest.raises(ValidationError, match="Invalid state transition"):
            ConnectionTransition(from_state=from_state, to_state=to_state)
